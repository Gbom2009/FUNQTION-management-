// Builds src/apps/maps/preflight.scoped.css: Tailwind's base reset (preflight),
// with every selector limited to the Maps root (.fq-maps), so it never touches
// the other apps. Re-run after a Tailwind upgrade: node scripts/maps/scope-preflight.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import postcss from "postcss";

const require = createRequire(import.meta.url);
const src = readFileSync(require.resolve("tailwindcss/preflight.css"), "utf8");
const ROOT = ".fq-maps";

const scope = (sel) => {
  const s = sel.trim();
  if (/^(html|:host|body)$/.test(s)) return ROOT;
  if (/^(html|:host|body)\b/.test(s)) return s.replace(/^(html|:host|body)/, ROOT);
  return `${ROOT} ${s}`;
};

const root = postcss.parse(src);
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.flatMap((s) => {
    const out = scope(s);
    // `*` should also reset the root itself (box-sizing, margins).
    return s.trim() === "*" ? [ROOT, out] : [out];
  });
});
writeFileSync(
  new URL("../../src/apps/maps/preflight.scoped.css", import.meta.url),
  `/* Generated by scripts/maps/scope-preflight.mjs from tailwindcss/preflight.css. Do not edit. */\n${root.toString()}`,
);
